/**
 * Имена, которыми объявлен любой контрол ввода: класс контейнера и состояния, которые база
 * ставит на него сама.
 *
 * Отдельным модулем и без единого импорта — так же во всех пакетах кита: имена нужны и базе,
 * и наследникам, и стилям потребителя, а модуль базы тянет за собой `@brandup/ui` и стили.
 *
 * Соглашение об именах — в `@brandup/ui-kit/names`.
 *
 * Одним объектом, а не россыпью констант: потребитель пишет `INPUT.CLASS.STATE.INVALID` и по пути
 * видит, что бывает рядом, а новое имя не разрастается в ещё один экспорт.
 */
export const INPUT = {
	CLASS: {
		/** Контейнер контрола — его база вешает на элемент при сборке. */
		ROOT: "ui-input",
		/**
		 * Пузырь с сообщением об ошибке. База создаёт его сама — но только если хост не дал
		 * своего места под текст (см. {@link INPUT.ATTR.ERROR}) и только под первое сообщение:
		 * у контрола, ни разу не отказавшего, лишнего узла в разметке не появляется.
		 */
		ERROR: "ui-input-error",
		/**
		 * Состояния контейнера: первые три отражают атрибуты поля-носителя, `INVALID` ставится
		 * по отказу браузера на проверке, `FOCUSED` — пока правят содержимое.
		 *
		 * Кит оформляет не все: обязательность — не про вид поля, а про требование к форме, и
		 * показывают её по-разному (звёздочка у подписи, пометка в сводке ошибок), поэтому
		 * `REQUIRED` остаётся зацепкой для хоста. Остальные оформлены (см. inputs.less).
		 */
		STATE: {
			/** Только зацепка для стилей хоста — сам кит по нему ничего не рисует. */
			REQUIRED: "required",
			READONLY: "readonly",
			DISABLED: "disabled",
			INVALID: "invalid",
			FOCUSED: "focused",
		},
	},
	ATTR: {
		/**
		 * Место под сообщение об ошибке. Читается двумя способами: атрибут на любом потомке
		 * контрола означает «пиши сюда», атрибут со значением на самом контроле — идентификатор
		 * элемента где угодно в документе (сводка ошибок под формой, ячейка соседней колонки).
		 *
		 * База в этот элемент только пишет: заполняет текстом, снимает `hidden` и связывает его
		 * с полем через `aria-describedby`. Ни создавать, ни удалять чужой элемент она не станет —
		 * он принадлежит разметке хоста, и раскладку вокруг него хост держит сам.
		 */
		ERROR: "data-input-error",
		/**
		 * Где показывать сообщение. По умолчанию — только в месте хоста (см. {@link INPUT.ATTR.ERROR}):
		 * раскладка страницы принадлежит ему, и заводить в ней узлы по своему усмотрению кит
		 * не станет. Нет места — нет и текста; отметка состояния и `aria-invalid` остаются,
		 * и по ним хост показывает отказ как ему удобно.
		 *
		 * `popup` — просьба нарисовать пузырь у контрола, когда места нет и взять его негде.
		 * `none` — не показывать вовсе, даже если место нашлось.
		 */
		ERROR_DISPLAY: "data-input-error-display",
	},
} as const;
