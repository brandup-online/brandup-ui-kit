/**
 * Имена, которыми кит объявлен в разметке: классы, команды и подписи попапа, модального окна
 * и прокручиваемой области.
 *
 * Отдельным модулем — и намеренно почти без импортов: имена нужны каждому пакету кита
 * (`.ui-popup` ищет в клике поле сообщения, `.ui-scrollable` вешают на свои списки редактор
 * и дропдаун), а общий вход кита тянет за собой попап, модальное окно, стили и `@brandup/ui-app`.
 * Ради одной строки класса это лишнее — отсюда имена приходят сами по себе. Единственный импорт —
 * реестр подписей (`./i18n`): он сам без импортов и без побочных эффектов.
 *
 * Одним объектом, а не россыпью констант: потребитель пишет `UIKIT.MODAL.COMMAND.CLOSE` и по пути
 * видит, что бывает рядом, а новое имя не разрастается в ещё один экспорт.
 *
 * Соглашение об именах — одно на все пакеты кита; длина имени показывает, откуда его видно:
 *
 *   `ui-<блок>` и `ui-<блок>-<часть>` — то, что видно вне корня контрола: сам корень, попап
 *   и окно в `body`, панель форматирования, поле-носитель (его пишет в разметке хост, чтобы поле
 *   не мелькало до инициализации). Такое имя обязано быть уникальным на всей странице.
 *
 *   короткое имя — часть внутри своего корня (`modal-window`, `decorator`, `emoji-group`)
 *   и состояние (`invalid`, `expanded`). Их всегда пишут вложенно, и повторять в них имя пакета
 *   незачем; имя под-блока в коротком остаётся, когда одно слово слишком общее: `toolbar-button`,
 *   а не `button`.
 *
 *   `body-<...>-opened` — состояние всей страницы, его ищут на `body` (см. `layer.ts`).
 */
import { declareTexts } from "./i18n";

declare module "./i18n" {
	interface KitTexts {
		/** Подписи модального окна. */
		modal: {
			/** Подпись крестика в шапке. */
			CLOSE: string;
		};
	}
}

